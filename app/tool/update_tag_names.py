"""Refresh the bundled tag names from DLsite and ASMR.ONE public metadata."""

import argparse
import json
from pathlib import Path
from urllib.request import Request, urlopen


def fetch_json(url, locale=None):
    headers = {"User-Agent": "Mozilla/5.0", "Accept": "application/json"}
    if locale:
        headers["Cookie"] = f"locale={locale}"
    with urlopen(Request(url, headers=headers), timeout=30) as response:
        return json.load(response)


def read_source(directory, filename, url, locale=None):
    if directory:
        text = (directory / filename).read_text(encoding="utf-8").strip()
        if text.startswith("```"):
            text = text[text.index("\n") + 1:text.rfind("```")]
        return json.loads(text)
    return fetch_json(url, locale)


def generate(directory=None):
    names = {}
    aliases = {}
    for locale in ["en_US", "ja_JP", "zh_CN", "zh_TW", "ko_KR"]:
        data = read_source(
            directory, f"dlsite-{locale}.json",
            "https://www.dlsite.com/maniax/fs/=/api_access/1", locale,
        )
        groups = data["genre_all"]
        if isinstance(groups, dict):
            groups = groups.values()
        for group in groups:
            for genre in group["values"]:
                tag_id = str(int(genre["value"]))
                name = genre["name"].strip()
                if name:
                    names.setdefault(tag_id, {})[locale.lower().replace("_", "-")] = name
                    aliases.setdefault(name, tag_id)

    # ONE supplies the names shown by its frontend, including historical aliases.
    tags = read_source(directory, "asmr-tags.md", "https://api.asmr.one/api/tags/")
    for tag in tags:
        tag_id = str(tag["id"])
        translations = names.setdefault(tag_id, {})
        for locale, value in tag.get("i18n", {}).items():
            if name := (value.get("name") or "").strip():
                translations[locale] = name
                aliases[name] = tag_id
            for old in value.get("history", []):
                if name := (old.get("name") or "").strip():
                    aliases[name] = tag_id
        if name := tag.get("name", "").strip():
            aliases[name] = tag_id

    def dart_json(value):
        return json.dumps(value, ensure_ascii=False, indent=2).replace("$", r"\$")

    names = dict(sorted(names.items(), key=lambda pair: int(pair[0])))
    aliases = dict(sorted(aliases.items()))
    output = Path(__file__).resolve().parents[1] / "lib/l10n/tag_names_data.dart"
    output.write_text(
        "// Generated by tool/update_tag_names.py. Do not edit by hand.\n"
        "// Sources: https://api.asmr.one/api/tags/ and\n"
        "// https://www.dlsite.com/maniax/fs/=/api_access/1 (locale cookie).\n\n"
        "const tagNamesById = <String, Map<String, String>>" + dart_json(names) + ";\n\n"
        "const tagIdsByAlias = <String, String>" + dart_json(aliases) + ";\n",
        encoding="utf-8",
    )
    print(f"Generated {len(names)} tags and {len(aliases)} aliases: {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, help="Use saved source responses")
    generate(parser.parse_args().source_dir)
